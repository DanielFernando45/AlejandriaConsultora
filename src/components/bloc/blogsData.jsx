// Función para obtener un blog por ID
export const getBlogById = (id) => {
  return blogsData.find(blog => blog.id === id);
};

// Función para obtener blogs por categoría
export const getBlogsByCategory = (category) => {
  return blogsData.filter(blog => blog.category === category);
};

// Función para buscar blogs por término
export const searchBlogs = (term) => {
  const lowerTerm = term.toLowerCase();
  return blogsData.filter(blog => 
    blog.title.toLowerCase().includes(lowerTerm) ||
    blog.excerpt.toLowerCase().includes(lowerTerm) ||
    blog.content.toLowerCase().includes(lowerTerm) ||
    blog.category.toLowerCase().includes(lowerTerm)
  );
};

// Obtener todas las categorías únicas
export const getAllCategories = () => {
  const categories = blogsData.map(blog => blog.category);
  return [...new Set(categories)];
};

